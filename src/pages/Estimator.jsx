  // Active feature addons sum
  const featureAddonsTotal = useMemo(() => {
    return FEATURES.filter((f) => selectedFeatures.includes(f.id)).reduce(
      (sum, f) => sum + f.cost,
      0
    );
  }, [selectedFeatures]);

  // Current calculated estimate
